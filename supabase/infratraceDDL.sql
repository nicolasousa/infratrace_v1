-- =====================================================================
-- InfraTrace — DDL (PostgreSQL / Supabase)
-- Gestão de ativos de datacenter
-- Convenções: snake_case, prefixo de 3 letras por tabela, FKs como fk_<prefixo>_id
-- =====================================================================

-- Necessária para as exclusion constraints (slots e aluguéis sobrepostos)
CREATE EXTENSION IF NOT EXISTS btree_gist;

-- ---------------------------------------------------------------------
-- Cadastros auxiliares
-- ---------------------------------------------------------------------
CREATE TABLE tipo_ativo (
    tpa_id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tpa_nome      VARCHAR(128) NOT NULL UNIQUE,
    tpa_descricao VARCHAR(512)
);

CREATE TABLE tipo_cliente (
    tpc_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tpc_nome VARCHAR(128) NOT NULL UNIQUE
);

-- Prazos de alerta configuráveis (RF-03.4 e RF-07.5)
CREATE TABLE configuracao (
    cfg_chave     VARCHAR(64)  PRIMARY KEY,
    cfg_valor     VARCHAR(256) NOT NULL,
    cfg_descricao VARCHAR(512)
);

-- ---------------------------------------------------------------------
-- Usuários e auditoria (RF-05)
-- ---------------------------------------------------------------------
CREATE TABLE usuario (
    usr_id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usr_nome              VARCHAR(128) NOT NULL,
    usr_email             VARCHAR(128) NOT NULL UNIQUE,
    usr_senha_hash        VARCHAR(255) NOT NULL,          -- hash BCrypt/Argon2, nunca texto puro
    usr_perfil            VARCHAR(16)  NOT NULL
                          CHECK (usr_perfil IN ('ADMIN', 'TECNICO', 'AUDITOR')),
    usr_ativo             BOOLEAN      NOT NULL DEFAULT TRUE,
    usr_token_recuperacao VARCHAR(255),
    usr_token_expiracao   TIMESTAMPTZ,
    usr_criado_em         TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);

CREATE TABLE log_auditoria (
    log_id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    log_acao           VARCHAR(16)  NOT NULL
                       CHECK (log_acao IN ('INSERT', 'UPDATE', 'DELETE', 'INATIVAR')),
    log_entidade       VARCHAR(128) NOT NULL,
    log_entidade_id    INTEGER      NOT NULL,
    log_data_hora      TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    log_valor_anterior TEXT,
    log_valor_novo     TEXT,
    fk_usr_id          INTEGER      NOT NULL REFERENCES usuario (usr_id)
);

-- ---------------------------------------------------------------------
-- Infraestrutura física (RF-02): sala → fileira → rack
-- ---------------------------------------------------------------------
CREATE TABLE sala (
    sal_id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sal_nome      VARCHAR(128) NOT NULL UNIQUE,
    sal_descricao VARCHAR(512)
);

CREATE TABLE fileira (
    fil_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fil_nome  VARCHAR(10) NOT NULL,
    fk_sal_id INTEGER     NOT NULL REFERENCES sala (sal_id),
    UNIQUE (fk_sal_id, fil_nome)
);

CREATE TABLE rack (
    rac_id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rac_nome        VARCHAR(128) NOT NULL,
    rac_total_slots INTEGER      NOT NULL CHECK (rac_total_slots BETWEEN 1 AND 60),
    fk_fil_id       INTEGER      NOT NULL REFERENCES fileira (fil_id),
    UNIQUE (fk_fil_id, rac_nome)
);

-- ---------------------------------------------------------------------
-- Ativos (RF-01, RF-02.4, RF-02.5, RF-03.1, RF-03.5)
-- ---------------------------------------------------------------------
CREATE TABLE nota_fiscal (
    nff_id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nff_num          INTEGER       NOT NULL,
    nff_chave        VARCHAR(44)   UNIQUE,
    nff_valor        DECIMAL(10,2) NOT NULL CHECK (nff_valor >= 0),
    nff_volumes      INTEGER,
    nff_razao_social VARCHAR(128)  NOT NULL,
    nff_cnpj         CHAR(14)      NOT NULL,
    nff_endereco     VARCHAR(128),
    nff_inscricao    VARCHAR(128),
    nff_descricao    VARCHAR(128)
);

CREATE TABLE ativo (
    atv_id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    atv_nome            VARCHAR(128)  NOT NULL,
    atv_fabricante      VARCHAR(128)  NOT NULL,
    atv_modelo          VARCHAR(128)  NOT NULL,
    atv_num_serie       VARCHAR(64)   NOT NULL UNIQUE,
    atv_patrimonio      VARCHAR(32)   UNIQUE,
    atv_status          VARCHAR(32)   NOT NULL DEFAULT 'ATIVO'
                        CHECK (atv_status IN ('ATIVO', 'INATIVO', 'EM_MANUTENCAO',
                                              'AGUARDANDO_DESCARTE', 'DESCARTADO')),
    atv_data_aquisicao  DATE,
    atv_valor_compra    DECIMAL(10,2) CHECK (atv_valor_compra >= 0),
    atv_garantia        DATE,                              -- data de vencimento da garantia
    atv_slot_inicio     INTEGER,
    atv_slot_fim        INTEGER,
    atv_data_descarte   DATE,
    atv_motivo_descarte VARCHAR(512),
    atv_criado_em       TIMESTAMPTZ   NOT NULL DEFAULT NOW(),
    fk_tpa_id           INTEGER       NOT NULL REFERENCES tipo_ativo (tpa_id),
    fk_rac_id           INTEGER       REFERENCES rack (rac_id),          -- nulo = fora de rack (estoque)
    fk_nff_id           INTEGER       REFERENCES nota_fiscal (nff_id),

    -- Rack e slots andam juntos: ou tudo preenchido, ou tudo vazio
    CONSTRAINT ck_atv_localizacao CHECK (
        (fk_rac_id IS NULL AND atv_slot_inicio IS NULL AND atv_slot_fim IS NULL)
        OR
        (fk_rac_id IS NOT NULL AND atv_slot_inicio IS NOT NULL AND atv_slot_fim IS NOT NULL
         AND atv_slot_inicio >= 1 AND atv_slot_fim >= atv_slot_inicio)
    ),
    -- Ativo descartado precisa de data e motivo, e não ocupa rack
    CONSTRAINT ck_atv_descarte CHECK (
        atv_status <> 'DESCARTADO'
        OR (atv_data_descarte IS NOT NULL AND atv_motivo_descarte IS NOT NULL AND fk_rac_id IS NULL)
    ),
    -- RF-02.5: dois ativos não podem ocupar intervalos de slots sobrepostos no mesmo rack
    CONSTRAINT ex_atv_slot_sobreposto EXCLUDE USING gist (
        fk_rac_id WITH =,
        int4range(atv_slot_inicio, atv_slot_fim, '[]') WITH &&
    ) WHERE (fk_rac_id IS NOT NULL)
);

-- RF-02.5 (complemento): slot final não pode passar da capacidade do rack
CREATE OR REPLACE FUNCTION fn_valida_capacidade_rack()
RETURNS TRIGGER AS $$
DECLARE
    v_total INTEGER;
BEGIN
    IF NEW.fk_rac_id IS NOT NULL THEN
        SELECT rac_total_slots INTO v_total FROM rack WHERE rac_id = NEW.fk_rac_id;
        IF NEW.atv_slot_fim > v_total THEN
            RAISE EXCEPTION 'Slot final (%) excede a capacidade do rack (% U)',
                NEW.atv_slot_fim, v_total;
        END IF;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER tg_ativo_capacidade_rack
BEFORE INSERT OR UPDATE OF fk_rac_id, atv_slot_inicio, atv_slot_fim ON ativo
FOR EACH ROW EXECUTE FUNCTION fn_valida_capacidade_rack();

-- Impede reduzir a capacidade de um rack abaixo de um ativo já instalado
CREATE OR REPLACE FUNCTION fn_valida_reducao_rack()
RETURNS TRIGGER AS $$
DECLARE
    v_maior_slot INTEGER;
BEGIN
    SELECT MAX(atv_slot_fim) INTO v_maior_slot FROM ativo WHERE fk_rac_id = NEW.rac_id;
    IF v_maior_slot > NEW.rac_total_slots THEN
        RAISE EXCEPTION 'Rack possui ativo ocupando até o slot %; capacidade não pode ser % U',
            v_maior_slot, NEW.rac_total_slots;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER tg_rack_reducao_capacidade
BEFORE UPDATE OF rac_total_slots ON rack
FOR EACH ROW EXECUTE FUNCTION fn_valida_reducao_rack();

-- Anexos do ativo (RF-01.5): nota fiscal, manual, contrato etc.
CREATE TABLE anexo (
    anx_id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    anx_tipo          VARCHAR(32)  NOT NULL
                      CHECK (anx_tipo IN ('NOTA_FISCAL', 'MANUAL', 'CONTRATO', 'OUTRO')),
    anx_nome_original VARCHAR(255) NOT NULL,
    anx_caminho       VARCHAR(512) NOT NULL,               -- caminho no storage
    anx_enviado_em    TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    fk_atv_id         INTEGER      NOT NULL REFERENCES ativo (atv_id)
);

-- ---------------------------------------------------------------------
-- Manutenção (RF-03.2, RF-03.3)
-- ---------------------------------------------------------------------
CREATE TABLE manutencao (
    man_id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    man_tipo        VARCHAR(16)  NOT NULL CHECK (man_tipo IN ('PREVENTIVA', 'CORRETIVA')),
    man_descricao   VARCHAR(512) NOT NULL,
    man_responsavel VARCHAR(128) NOT NULL,                 -- quem executou (pode ser técnico externo)
    man_data_inicio DATE         NOT NULL,
    man_data_fim    DATE,                                  -- nulo = em andamento
    fk_atv_id       INTEGER      NOT NULL REFERENCES ativo (atv_id),
    fk_usr_id       INTEGER      NOT NULL REFERENCES usuario (usr_id),  -- quem registrou no sistema
    CONSTRAINT ck_man_datas CHECK (man_data_fim IS NULL OR man_data_fim >= man_data_inicio)
);

-- ---------------------------------------------------------------------
-- Movimentação física (RF-02.7)
-- ---------------------------------------------------------------------
CREATE TABLE movimentacao (
    mov_id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mov_data                TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    mov_motivo              VARCHAR(512),
    mov_slot_inicio_origem  INTEGER,
    mov_slot_fim_origem     INTEGER,
    mov_slot_inicio_destino INTEGER,
    mov_slot_fim_destino    INTEGER,
    fk_rac_origem_id        INTEGER      REFERENCES rack (rac_id),   -- nulo = veio do estoque
    fk_rac_destino_id       INTEGER      REFERENCES rack (rac_id),   -- nulo = foi para o estoque
    fk_atv_id               INTEGER      NOT NULL REFERENCES ativo (atv_id),
    fk_usr_id               INTEGER      NOT NULL REFERENCES usuario (usr_id),
    CONSTRAINT ck_mov_tem_rack CHECK (fk_rac_origem_id IS NOT NULL OR fk_rac_destino_id IS NOT NULL),
    CONSTRAINT ck_mov_origem CHECK (
        (fk_rac_origem_id IS NULL AND mov_slot_inicio_origem IS NULL AND mov_slot_fim_origem IS NULL)
        OR (fk_rac_origem_id IS NOT NULL
            AND mov_slot_inicio_origem IS NOT NULL AND mov_slot_fim_origem IS NOT NULL
            AND mov_slot_inicio_origem >= 1 AND mov_slot_fim_origem >= mov_slot_inicio_origem)
    ),
    CONSTRAINT ck_mov_destino CHECK (
        (fk_rac_destino_id IS NULL AND mov_slot_inicio_destino IS NULL AND mov_slot_fim_destino IS NULL)
        OR (fk_rac_destino_id IS NOT NULL
            AND mov_slot_inicio_destino IS NOT NULL AND mov_slot_fim_destino IS NOT NULL
            AND mov_slot_inicio_destino >= 1 AND mov_slot_fim_destino >= mov_slot_inicio_destino)
    )
);

-- Slot de destino da movimentação não pode passar da capacidade do rack
CREATE OR REPLACE FUNCTION fn_valida_capacidade_movimentacao()
RETURNS TRIGGER AS $$
DECLARE
    v_total INTEGER;
BEGIN
    IF NEW.fk_rac_destino_id IS NOT NULL THEN
        SELECT rac_total_slots INTO v_total FROM rack WHERE rac_id = NEW.fk_rac_destino_id;
        IF NEW.mov_slot_fim_destino > v_total THEN
            RAISE EXCEPTION 'Slot final de destino (%) excede a capacidade do rack (% U)',
                NEW.mov_slot_fim_destino, v_total;
        END IF;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER tg_movimentacao_capacidade_rack
BEFORE INSERT OR UPDATE ON movimentacao
FOR EACH ROW EXECUTE FUNCTION fn_valida_capacidade_movimentacao();

-- Observação: a movimentação NÃO altera o ativo sozinha. A aplicação deve,
