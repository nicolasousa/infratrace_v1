-- ---------------------------------------------------------------------
-- Clientes e aluguéis (RF-06, RF-07)
-- ---------------------------------------------------------------------
CREATE TABLE cliente (
    cli_id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cli_nome          VARCHAR(200) NOT NULL,
    cli_cnpj          CHAR(14)     NOT NULL UNIQUE,        -- somente dígitos
    cli_representante VARCHAR(128) NOT NULL,
    cli_ativo         BOOLEAN      NOT NULL DEFAULT TRUE,
    fk_tpc_id         INTEGER      NOT NULL REFERENCES tipo_cliente (tpc_id),
    CONSTRAINT ck_cli_cnpj CHECK (cli_cnpj ~ '^[0-9]{14}$')
);

CREATE TABLE aluguel (
    alu_id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alu_data_inicio DATE          NOT NULL,
    alu_data_fim    DATE          NOT NULL,
    alu_valor       DECIMAL(10,2) NOT NULL CHECK (alu_valor >= 0),   -- valor mensal
    fk_cli_id       INTEGER       NOT NULL REFERENCES cliente (cli_id),
    fk_rac_id       INTEGER       NOT NULL REFERENCES rack (rac_id),
    CONSTRAINT ck_alu_datas CHECK (alu_data_fim >= alu_data_inicio),
    -- RF-07.2: o mesmo rack não pode ter aluguéis com períodos sobrepostos
    CONSTRAINT ex_alu_periodo_sobreposto EXCLUDE USING gist (
        fk_rac_id WITH =,
        daterange(alu_data_inicio, alu_data_fim, '[]') WITH &&
    )
);

